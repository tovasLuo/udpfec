/**
 * @brief Create combined hash using default algorithm (MurmurHash3)
 * @tparam Args Types of values to hash
 * @param args Values to compute hash for
 * @return Combined hash value
 */
template <typename... Args>
inline size_t make_hash(const Args&... args) {
    return hash_combiner::make_hash<hash_combiner::murmur3_hash>(args...);
}

